/*Exercício 03 — Comparações
Considere:
    let idade = 20;
Crie expressões que respondam:
    A idade é maior que 18?
    A idade é menor que 18?
    A idade é exatamente 20?
    A idade é diferente de 25?
    A idade é maior ou igual a 21?
    A idade é menor ou igual a 20?
O resultado de cada comparação deve ser true ou false.*/
let idade = 20;

console.log("Maior que 18:", idade > 18);
console.log("Menor que 18:", idade < 18);
console.log("Exatamente 20:", idade === 20);
console.log("Diferente de 25:", idade !== 25);
console.log("Maior ou igual a 21:", idade >= 21);
console.log("Menor ou igual a 20:", idade <= 20);
