/* Exercício 02 — Operadores de atribuição
Comece com:
    let saldo = 1000;
Faça exatamente nesta ordem:
    + 500
    - 200
    * 2
    / 4
Use obrigatoriamente:
    +=
    -=
    *=
    /=
No final, mostre o saldo.
Pergunta: qual será o resultado? */
let saldo = 1000;
saldo += 500;
saldo -= 200;
saldo *= 2;
saldo /= 4;
console.log("Pergunta: qual será o resultado?");
console.log("Resposta: saldo = ", saldo);
